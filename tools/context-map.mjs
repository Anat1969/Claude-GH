#!/usr/bin/env node
// Context map: read once, navigate the map afterwards.
// Zero LLM tokens: everything here is deterministic parsing.
//
//   node tools/context-map.mjs instructions          splits CLAUDE.md and the skills into
//                                                   context/sections/*.md + context/INDEX.md
//   node tools/context-map.mjs code <repoDir>        writes <repoDir>/CODEMAP.md
//   node tools/context-map.mjs check                 exits 1 when context/ is stale
//
// Token figures are estimates: Latin text ~4 chars per token, Hebrew ~2 chars per token.

import fs from 'node:fs';
import path from 'node:path';
import { execSync } from 'node:child_process';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const RAW = 'https://raw.githubusercontent.com/Anat1969/Claude-GH/main/';
const SOURCES = [
  { id: 'cl', file: 'CLAUDE.md', name: 'הנחיות־העל' },
  { id: 'ab', file: '.claude/skills/anat-app-builder/SKILL.md', name: 'בניית אפליקציות' },
  { id: 'dl', file: '.claude/skills/anat-design-language/SKILL.md', name: 'שפת העיצוב' },
];
const SPLIT_LIMIT = 5000; // a "##" section larger than this is split again at "###"

export function estTokens(text) {
  let he = 0;
  for (const c of text) if (c >= '֐' && c <= '׿') he++;
  return Math.round(he / 2 + (text.length - he) / 4);
}

// Stable ids follow the section number ("2.8" -> dl-2.8, "9ב" -> cl-9b), so routing
// in CORE.md survives when new sections are added.
const HEB = { 'א': 'a', 'ב': 'b', 'ג': 'c', 'ד': 'd', 'ה': 'e' };
const NAMED = { 'יומן תיקונים': 'log', 'למדנו בבנייה': 'learned' };
function numberOf(title) {
  const m = title && title.match(/^(\d+(?:\.\d+)*)([א-ה])?[.\s]/);
  return m ? m[1] + (m[2] ? HEB[m[2]] : '') : null;
}
function stableId(title, parentTitle, isPart, n) {
  if (isPart && !title) return (numberOf(parentTitle) || `s${n}`) + '.0';
  if (!title) return 'intro';
  return numberOf(title) || NAMED[title.trim()] || `s${n}`;
}

function splitBy(lines, marker) {
  const out = [];
  let cur = { title: null, lines: [] };
  let fence = false;
  for (const l of lines) {
    if (l.startsWith('```')) fence = !fence;
    if (!fence && l.startsWith(marker) && !l.startsWith(marker + '#')) {
      if (cur.title !== null || cur.lines.some((x) => x.trim())) out.push(cur);
      cur = { title: l.slice(marker.length).trim(), lines: [l] };
    } else cur.lines.push(l);
  }
  out.push(cur);
  return out;
}

function buildInstructions() {
  const files = {};
  const rows = [];
  let total = 0;
  for (const src of SOURCES) {
    const text = fs.readFileSync(path.join(ROOT, src.file), 'utf8');
    total += estTokens(text);
    let n = 0;
    for (const sec of splitBy(text.split('\n'), '## ')) {
      let parts = sec.lines.join('\n').length > SPLIT_LIMIT ? splitBy(sec.lines, '### ') : [sec];
      if (parts.length === 1) parts = [sec];
      for (const p of parts) {
        const body = p.lines.join('\n').trim();
        if (!body) continue;
        const id = `${src.id}-${stableId(p.title, sec.title, p !== sec, n++)}`;
        const clean = (t) => t.replace(/\s*\([^)]*\)\s*$/, '').replace(/\|/g, '/');
        const title = clean(p.title || 'פתיחה');
        const parent = p !== sec && sec.title ? `${clean(sec.title)} / ` : '';
        const header = `<!-- generated by tools/context-map.mjs from ${src.file}; edit the source, not this file -->\n`;
        if (files[`context/sections/${id}.md`]) throw new Error(`duplicate section id ${id} in ${src.file}`);
        files[`context/sections/${id}.md`] = header + body + '\n';
        const tok = estTokens(body);
        rows.push(`| \`${id}\` | ${src.name}: ${parent}${title} | ${tok} | ${RAW}context/sections/${id}.md |`);
      }
    }
  }
  const core = fs.readFileSync(path.join(ROOT, 'context/CORE.md'), 'utf8');
  files['context/INDEX.md'] = [
    '<!-- generated by tools/context-map.mjs; run `node tools/context-map.mjs instructions` after editing a source -->',
    '# מפת ההנחיות',
    '',
    'קוראים את `context/CORE.md`, ואחריו רק את הסעיפים שהמשימה צריכה.',
    `הטעינה המלאה של שלושת המקורות: כ-**${total}** טוקנים. הליבה לבדה: כ-**${estTokens(core)}** טוקנים (הערכה).`,
    '',
    '| מזהה | סעיף | טוקנים (הערכה) | כתובת |',
    '|---|---|---|---|',
    ...rows,
    '',
  ].join('\n');
  return files;
}

function writeAll(files) {
  fs.rmSync(path.join(ROOT, 'context/sections'), { recursive: true, force: true });
  for (const [rel, body] of Object.entries(files)) {
    fs.mkdirSync(path.dirname(path.join(ROOT, rel)), { recursive: true });
    fs.writeFileSync(path.join(ROOT, rel), body);
  }
  console.log(`wrote ${Object.keys(files).length} files`);
}

function check() {
  const files = buildInstructions();
  const dir = path.join(ROOT, 'context/sections');
  const existing = fs.existsSync(dir) ? fs.readdirSync(dir).map((f) => `context/sections/${f}`) : [];
  const stale = Object.entries(files).filter(([rel, body]) => {
    const p = path.join(ROOT, rel);
    return !fs.existsSync(p) || fs.readFileSync(p, 'utf8') !== body;
  }).map(([rel]) => rel);
  const extra = existing.filter((rel) => !(rel in files));
  const core = fs.readFileSync(path.join(ROOT, 'context/CORE.md'), 'utf8');
  const missing = [...core.matchAll(/`((?:cl|ab|dl)-[\w.]+)`/g)].map((m) => m[1]).filter((id) => !(`context/sections/${id}.md` in files));
  if (missing.length) {
    console.error(`CORE.md routes to sections that do not exist: ${missing.join(', ')}`);
    process.exit(1);
  }
  if (stale.length || extra.length) {
    console.error('context/ is stale. Run: node tools/context-map.mjs instructions');
    console.error([...stale, ...extra].join('\n'));
    process.exit(1);
  }
  console.log('context/ is up to date');
}

// ---------- code map ----------
const CODE_EXT = /\.(tsx?|jsx?|mjs|cjs|vue|svelte|py|sql|css|html)$/;
const SKIP = /(^|\/)(node_modules|dist|build|\.next|coverage|vendor|gh-pages)\//;

function listFiles(dir) {
  try {
    return execSync('git ls-files', { cwd: dir, encoding: 'utf8' }).split('\n').filter(Boolean);
  } catch {
    const out = [];
    const walk = (d) => {
      for (const e of fs.readdirSync(path.join(dir, d), { withFileTypes: true })) {
        const rel = path.posix.join(d, e.name);
        if (e.name.startsWith('.') || SKIP.test(rel + '/')) continue;
        e.isDirectory() ? walk(rel) : out.push(rel);
      }
    };
    walk('.');
    return out.map((f) => f.replace(/^\.\//, ''));
  }
}

function symbols(rel, text) {
  const s = new Set();
  const add = (re) => { for (const m of text.matchAll(re)) s.add(m[1]); };
  if (/\.(tsx?|jsx?|mjs|cjs)$/.test(rel)) {
    add(/^export\s+(?:default\s+)?(?:async\s+)?(?:function\*?|class|const|let|interface|type|enum)\s+([A-Za-z_$][\w$]*)/gm);
    add(/^(?:async\s+)?function\s+([A-Za-z_$][\w$]*)/gm);
    add(/customElements\.define\(\s*['"]([\w-]+)['"]/g);
    if (/^export\s+default\s+[A-Za-z_$]/m.test(text) && !s.size) s.add('default');
  } else if (/\.(html|vue|svelte)$/.test(rel)) {
    // code inside <script>: functions are usually indented, so the line start is not required
    add(/^\s*(?:async\s+)?function\s+([A-Za-z_$][\w$]*)/gm);
    add(/customElements\.define\(\s*['"]([\w-]+)['"]/g);
  } else if (rel.endsWith('.py')) {
    add(/^(?:def|class)\s+([A-Za-z_]\w*)/gm);
  } else if (rel.endsWith('.sql')) {
    add(/create\s+(?:or\s+replace\s+)?(?:table|view|function|policy)\s+(?:if\s+not\s+exists\s+)?([\w."]+)/gi);
  }
  return [...s];
}

// Large files get anchors: every function, constant and section comment with its line number,
// so a session opens a line range instead of the whole file (06.11.2026, learned in targil2:
// four HTML files of 100 to 1,500 lines were invisible to the map).
const ANCHOR_MIN_LINES = 300;
const ANCHORS = [
  [/^\s*(?:export\s+)?(?:default\s+)?(?:async\s+)?function\*?\s+([\w$]+)\s*\(/, (m) => m[1] + '()'],
  [/^\s*(?:export\s+)?class\s+([\w$]+)/, (m) => 'class ' + m[1]],
  [/^\s*(?:export\s+)?const\s+([\w$]+)\s*=\s*(?:async\s*)?(?:\([^)]*\)|[\w$]+)\s*=>/, (m) => m[1] + '()'],
  [/^\s*(?:export\s+)?(?:const|let)\s+([A-Z][A-Z0-9_]{2,})\s*=/, (m) => m[1]],
  [/^\s*\/\/\s*[-=]{3,}\s*(.+?)\s*[-=]{3,}\s*$/, (m) => '§ ' + m[1]],
  [/^\s*\/\*\s*[-=]{3,}\s*(.+?)\s*[-=]{3,}\s*\*\/\s*$/, (m) => '§ ' + m[1]],
  [/^\s*<(main|header|section|aside|nav|template)\b[^>]*\b(?:id|class)="([^"\s]+)/, (m) => '<' + m[1] + ' ' + m[2] + '>'],
  [/^\s*(?:def|class)\s+([A-Za-z_]\w*)/, (m) => m[1]],
];
function anchors(text) {
  const out = [];
  text.split('\n').forEach((l, i) => { for (const [re, name] of ANCHORS) { const m = l.match(re); if (m) { out.push(`${i + 1} ${name(m)}`); break; } } });
  return out;
}

function localImports(rel, text) {
  const out = new Set();
  for (const m of text.matchAll(/(?:import|export)[^'"]*?from\s+['"](\.[^'"]+)['"]|import\(\s*['"](\.[^'"]+)['"]\s*\)/g)) {
    const spec = m[1] || m[2];
    out.add(path.posix.normalize(path.posix.join(path.posix.dirname(rel), spec)).replace(/\.(tsx?|jsx?)$/, ''));
  }
  return [...out];
}

function buildCodeMap(dir) {
  const files = listFiles(dir).filter((f) => CODE_EXT.test(f) && !SKIP.test(f));
  const rows = [];
  const usedBy = {};
  const tables = new Set();
  let lines = 0;
  let readTokens = 0;
  const anchored = [];
  for (const rel of files) {
    const full = path.join(dir, rel);
    if (!fs.existsSync(full) || fs.statSync(full).size > 400_000) continue;
    const text = fs.readFileSync(full, 'utf8');
    const n = text.split('\n').length;
    lines += n;
    readTokens += estTokens(text);
    if (n >= ANCHOR_MIN_LINES) { const a = anchors(text); if (a.length) anchored.push({ rel, n, a }); }
    for (const m of text.matchAll(/\.from\(\s*['"]([\w-]+)['"]\s*\)|storage\s*\.from\(\s*['"]([\w-]+)['"]/g)) tables.add(m[1] || m[2]);
    for (const imp of localImports(rel, text)) (usedBy[imp] ??= []).push(rel);
    rows.push({ rel, n, syms: symbols(rel, text) });
  }
  const key = (rel) => rel.replace(/\.(tsx?|jsx?)$/, '').replace(/\/index$/, '');
  const dirs = {};
  for (const r of rows) (dirs[path.posix.dirname(r.rel)] ??= []).push(r);
  const name = path.basename(path.resolve(dir));
  const md = [
    `<!-- generated by Claude-GH/tools/context-map.mjs; regenerate, do not edit -->`,
    `# מפת הקוד: ${name}`,
    '',
    'קוראים את המפה הזו לפני פתיחת קבצים. פותחים רק את הקובץ שהמשימה צריכה, ובטווח שורות כשאפשר.',
    `**${rows.length}** קבצים, **${lines}** שורות. קריאה של הכול: כ-**${readTokens}** טוקנים. המפה: כ-**MAPTOK** טוקנים (הערכה).`,
    '',
  ];
  if (tables.size) md.push(`טבלאות ודליים שהקוד פונה אליהם: ${[...tables].sort().map((t) => `\`${t}\``).join(', ')}`, '');
  md.push('| קובץ | שורות | מה יש בו | מי משתמש בו |', '|---|---|---|---|');
  for (const d of Object.keys(dirs).sort()) {
    for (const r of dirs[d].sort((a, b) => a.rel.localeCompare(b.rel))) {
      const users = (usedBy[key(r.rel)] || usedBy[r.rel.replace(/\.(tsx?|jsx?)$/, '')] || []).map((u) => path.posix.basename(u));
      const syms = r.syms.slice(0, 12).join(', ') + (r.syms.length > 12 ? ` (+${r.syms.length - 12})` : '');
      md.push(`| \`${r.rel}\` | ${r.n} | ${syms} | ${[...new Set(users)].slice(0, 6).join(', ')} |`);
    }
  }
  md.push('');
  if (anchored.length) {
    md.push(`## עוגנים בקבצים הגדולים (${ANCHOR_MIN_LINES} שורות ומעלה)`, '', 'פותחים בטווח שורות סביב העוגן (offset ו-limit), לא את כל הקובץ.', '');
    for (const f of anchored) md.push(`**\`${f.rel}\`** (${f.n}): ` + f.a.join(' · '), '');
  }
  let out = md.join('\n');
  out = out.replace('MAPTOK', String(estTokens(out)));
  fs.writeFileSync(path.join(dir, 'CODEMAP.md'), out);
  console.log(`CODEMAP.md: ${rows.length} files, ${lines} lines, ${anchored.length} anchored; map ~${estTokens(out)} tokens vs ~${readTokens} for reading everything`);
}

const [mode, arg] = process.argv.slice(2);
if (mode === 'instructions') writeAll(buildInstructions());
else if (mode === 'check') check();
else if (mode === 'code') buildCodeMap(arg || '.');
else {
  console.log('usage: context-map.mjs instructions | check | code <repoDir>');
  process.exit(2);
}
